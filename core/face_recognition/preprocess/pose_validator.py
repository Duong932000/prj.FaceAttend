class PoseValidator:
    @staticmethod
    def validate_pose(face, target_pose):
        yaw, pitch, roll = face.pose

        if target_pose == "front":
            return abs(yaw) < 10 and abs(pitch) < 10
        if target_pose == "left":
            return yaw < -15
        if target_pose == "right":
            return yaw > 15
        if target_pose == "up":
            return pitch > 10
        if target_pose == "down":
            return pitch < -10
        if target_pose in ["mask", "glasses"]:
            return abs(yaw) < 10
        
        return False
